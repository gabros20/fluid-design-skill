#!/usr/bin/env node
// generate-fluid.mjs — deterministic generator for every fluid-design style
// stack. Reads fluid.config.json (or the built-in defaults), and writes the
// stack files under assets/styles/. Re-running it with the same config
// produces byte-identical output: no timestamps, no non-deterministic
// ordering, no host-specific paths in the emitted text.
//
//   node generate-fluid.mjs [--config fluid.config.json] --stack tailwind-v4|css|scss|stylex|all [--out DIR] [--check]
//
// `--check` regenerates from the DEFAULT config (assets/fluid.config.json)
// and diffs the result against what's already on disk under assets/styles/,
// for every stack. It exits 1 and prints every differing/missing file if
// anything differs, 0 otherwise. It writes nothing.
//
// The committed assets/styles/* files are exactly this script's output for
// the default config — never hand-edit them; edit fluid.config.json (or this
// generator) and re-run.

