function rootBlock(units) {
  const lines = Object.entries(units.root).map(([k, v]) => `  ${k}: ${v};`)
  return `:root {\n${lines.join('\n')}\n}\n`
}

function engagedBlock(units, indent = '  ') {
  const lines = Object.entries(units.engaged).map(([k, v]) => `${indent}  ${k}: ${v};`)
  return `@media (width >= ${units.engageAt}px) {\n${indent}:root {\n${lines.join('\n')}\n${indent}}\n}\n`
}

