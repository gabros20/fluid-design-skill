function mdHeader(cfg, title) {
  const lines = configSummary(cfg)
  return `<!--\nGENERATED by fluid-design's generate-fluid.mjs — do not hand-edit.\nEdit fluid.config.json and re-run: node scripts/generate-fluid.mjs --stack ${title}\n\nConfig:\n${lines.map((l) => `  ${l}`).join('\n')}\n-->\n\n`
}

function rootBlock(units) {
  const lines = Object.entries(units.root).map(([k, v]) => `  ${k}: ${v};`)
  return `:root {\n${lines.join('\n')}\n}\n`
}

function engagedBlock(units, indent = '  ') {
  const lines = Object.entries(units.engaged).map(([k, v]) => `${indent}  ${k}: ${v};`)
  return `@media (width >= ${units.engageAt}px) {\n${indent}:root {\n${lines.join('\n')}\n${indent}}\n}\n`
}

const NOT_SCALED_NOTE = `NOT SCALED, deliberately:
  - border and stroke WIDTHS — a scaled 1px hairline is a blurry 1.5px one.
  - corner radii — there is nothing to scale on a square design.
  - tracking-*, letter-spacing — write it in \`em\`; that already follows
    font-size for free, so it never needs a fluid unit of its own.
  - standalone line-height outside the type utilities' own /lh modifier.
  - plain max-width TEXT MEASURES — those must stay fixed. A fixed measure
    is exactly why display type rides the gentler, damped curve instead of
    the base unit: a heading that shares a wrap-sensitive column with fixed
    body copy must not out-grow it.`

const UNITLESS_NOTE = `THE UNITLESS-NUMBER RULE: every value above is a bare number, never a
length. \`64px * var(--fluid)\` is invalid CSS — length multiplied by length
has no defined unit, so the browser drops the whole declaration, silently,
with no warning in the console. Always \`calc(64 * var(--fluid))\`: a
unitless number times a length (--fluid is 1px at the reference) resolves to
a length. This is the single most common way to lose one of these utilities
by hand-editing generated output — another reason not to.`

const NEGATIVES_NOTE = `NEGATIVES have no separate utility. Put the sign inside an arbitrary
value instead of doubling this file with a \`-<prefix>-top-*\` family that
only a handful of call sites would ever use:
  lg:top-[calc(-8*var(--fluid))]`

const ONE_SCALE_NOTE = `ONE SCALE, NO PER-SECTION RE-ANCHORING. A section drawn taller than the
reference cannot declare its own height as a local reference so that its
own \`N * var(--fluid)\` lands on 100svh again — that re-bases \`--fluid\`
without re-basing the type units with it (a rule that only sets --fluid
leaves --fluid-display on the ancestor's value; custom properties
substitute where they're DECLARED), so a display line's size would then
depend on how tall a NEIGHBOURING section happens to be drawn, not on the
viewport. A composition drawn taller than the reference is legitimately
more than one screen, at every viewport, by construction — making it fit is
a layout/content decision, not a units one.`

function floorAndArmNote(cfg) {
  const floors = resolveFloors(cfg)
  const ratio = num(cfg.engageAt / cfg.reference.width)
  return `WHY min(), NOT max(): the two axes must COMBINE as a "contain" fit — the
tighter axis wins — which is what makes "never taller than the viewport"
unconditional. max() would be "cover", letting a section outgrow the window
on whichever axis lost.

WHY svh, NOT dvh: dvh resizes as a mobile browser's chrome collapses
mid-scroll, which would resize type mid-gesture — over anything
scroll-driven, the worst possible surface for a layout thrash. svh is the
SMALLEST viewport height and does not move once the page has loaded.

FLOOR DERIVATION (the "auto" floors in fluid.config.json): a damped type
unit's floor is not picked, it is READ OFF the damped curve at \`engageAt\`
— the value the role hands over at the exact breakpoint where the whole
scale flattens to 1px and a fixed mobile layout takes over:
  engageAt / reference.width = ${ratio}
  display: ${num(cfg.units.display.damping)} * ${ratio} + ${num(1 - cfg.units.display.damping)} -> floor ${num(floors.display)}
  copy:    ${num(cfg.units.copy.damping)} * ${ratio} + ${num(1 - cfg.units.copy.damping)} -> floor ${num(floors.copy)}
The base --fluid floor (${num(floors.fluid)}) is different in kind: it is
CHOSEN, not derived — the layout height at which the composition itself
should stop compressing further — because the base unit has no upstream
curve to read a handover value from.

THE CHROME UNIT (--fluid-chrome): site chrome (header, footer, dropdowns)
must never shrink on a short-but-wide window, where height would otherwise
bind and shrink the whole layout unit — but it still has to shrink when
WIDTH binds, or it stops fitting at engageAt. That is width-always,
height-never-below-1: \`min(widthArm, max(1px, heightArm))\`. It is spent
explicitly at call sites (\`calc(N * var(--fluid-chrome))\`) — there is no
parallel \`${cfg.prefix}-chrome-*\` utility family, on purpose: chrome is a
small, fixed set of call sites, not a general layout concern.`
}

const FOUR_INVARIANTS_NOTE = `FOUR INVARIANTS. Breaking any one stops this being a scale:
  1. --fluid stays purely proportional on both arms, no intercept — that is
     what makes \`900 * var(--fluid)\` resolve to exactly \`100svh\` while
     height binds, landing a section on exactly one screen.
  2. \`reference\` is a CONTENT budget, not the drawn canvas — it is
     deliberately narrower than \`canvas.width\` so desktop content fits a
     typical window; between the two the composition does not scale at all
     (the height arm pins the factor at 1.0), it just gets more room.
  3. The two axes combine with min(), never max() — see below.
  4. svh, never dvh — see below.
Below \`engageAt\` every one of these is a flat 1px, so every value under
that breakpoint is completely untouched — the system is desktop-only by
design.`

