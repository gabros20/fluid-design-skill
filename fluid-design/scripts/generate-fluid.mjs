function buildTokensExampleCss(cfg) {
  return (
    cssHeader(cfg, 'tailwind-v4') +
    `/* tokens.example.css — an EXAMPLE, not your brand. Copy the shape, replace
   the ramp and the role aliases with your own palette. This is what "reach
   for the semantic name, not the brand ramp" (surface/text/border/icon
   roles aliasing a brand ramp) looks like wired up.
*/
@theme {
  /* MUST equal \`engageAt\` in fluid.config.json (${num(cfg.engageAt)} by default).
     fluid.css's own media query is hand-written as
     \`@media (width >= ${num(cfg.engageAt)}px)\` — it has no Tailwind config
     to read a breakpoint from — so if you move \`engageAt\` you must move
     this token by hand too, or the two silently disagree about where the
     site turns into a fixed 1px scale. */
  --breakpoint-lg: ${num(cfg.engageAt)}px;

  /* ── Brand ramp — replace ──────────────────────────────────────────── */
  --color-brand-navy-900: #0b1220;
  --color-brand-navy-700: #1c2b45;
  --color-brand-gold-500: #fccc36;
  --color-brand-neutral-white: #ffffff;
  --color-brand-neutral-black: #000000;

  /* ── Semantic roles — components use THESE, never the ramp above ─────
     Four traps below, all of which compile and render as plausible design
     decisions. None of them error — \`pnpm kit:lint\`-equivalent tooling (a
     lint rule banning raw brand-ramp classes outside this file) is what
     catches them, not the compiler. */
  --color-surface-dark: var(--color-brand-navy-900);
  --color-surface-light: var(--color-brand-neutral-white);
  --color-text-heading: var(--color-brand-neutral-white);
  --color-text-body: var(--color-brand-navy-700);
  --color-border-primary: var(--color-brand-navy-700);
  --color-icon-default: var(--color-brand-navy-700);
  --focus-ring: var(--color-brand-gold-500);

  /* Trap 1: \`rounded-*\` still rounds. Defining a token at 0 ADDS a utility
     (\`rounded-custom\`) — it does not reset Tailwind's existing radius
     scale, so \`rounded-lg\` etc. keep rounding right next to it. */
  --radius-custom: 0px;

  /* Trap 2: there is no \`dark:\` mode here (no \`@custom-variant dark\`
     declared), so if a component reaches for \`dark:bg-surface-dark\`
     anyway, Tailwind compiles it to a bare
     \`@media (prefers-color-scheme: dark)\` query that fires for every
     visitor whose OS theme is dark — not a manual toggle. Either declare
     \`@custom-variant dark\` for real, or never write \`dark:\` at all. */

  /* Trap 3: a utility whose token does not exist emits NOTHING and Tailwind
     never warns. \`bg-brand-teal-500\` with no \`--color-brand-teal-500\`
     above silently produces an empty rule — it looks wired up in the
     markup and does nothing in the browser. */

  /* Trap 4: a name shared with another codebase can mean something else
     there. \`--color-app-*\` in a sibling design-system package, or
     \`border-border-secondary\` in a different app, is not guaranteed to be
     this ramp — check before reusing a token NAME across projects. */
}
`
  )
}

function buildCnTs(cfg) {
  const p = cfg.prefix
  const groupsSpacing = [
    ['p', 'p'], ['px', 'px'], ['py', 'py'], ['pt', 'pt'], ['pb', 'pb'], ['pl', 'pl'], ['pr', 'pr'],
    ['m', 'm'], ['mx', 'mx'], ['my', 'my'], ['mt', 'mt'], ['mb', 'mb'], ['ml', 'ml'], ['mr', 'mr'],
    ['gap', 'gap'], ["'gap-x'", 'gap-x'], ["'gap-y'", 'gap-y']
  ]
  const spacingLines = groupsSpacing.map(([group, suffix]) => `      ${group}: [fluid('${p}-${suffix}')],`).join('\n')
  return (
    tsHeader(cfg, 'tailwind-v4') +
    `import { type ClassValue, clsx } from 'clsx'
import { extendTailwindMerge } from 'tailwind-merge'

/**
 * \`tailwind-merge\` resolves conflicts from a table of class groups it ships
 * with. \`${p}-*\` utilities are not in that table, so out of the box it
 * treats every one of them as an unknown class and keeps ALL of them:
 *
 *   twMerge('lg:${p}-p-40 lg:${p}-p-24')  ->  BOTH survive
 *   twMerge('lg:w-[380px] lg:${p}-w-560') ->  BOTH survive
 *
 * Two declarations of the same property then both reach the browser, and
 * CSS SOURCE ORDER decides which wins — not the order they were written in
 * the class string. That is the opposite of what every caller assumes when
 * they pass \`className\` to override a component's default, and it stays
 * invisible right up until a shared component starts accepting
 * \`className\` on top of its own fluid classes.
 *
 * So each family is registered into the Tailwind class group its property
 * already belongs to: \`${p}-p-*\` joins \`p\`, \`${p}-w-*\` joins \`w\`, and all
 * three font-size families join \`font-size\`, which additionally makes
 * them conflict with EACH OTHER — \`${p}-text-14 ${p}-copy-14\` then
 * resolves to the last one instead of shipping two font sizes.
 */

// Every fluid utility takes a bare number, optionally with Tailwind's \`/\`
// line-height modifier: \`${p}-p-40\`, \`${p}-text-14\`, \`${p}-text-14/18\`.
// Decimals are allowed — the scale accepts any drawn number.
const isFluidValue = (value: string) => /^\\d+(\\.\\d+)?(\\/\\d+(\\.\\d+)?)?$/.test(value)

const fluid = (name: string) => ({ [name]: [isFluidValue] })

export const twMerge = extendTailwindMerge({
  extend: {
    classGroups: {
      // Spacing
${spacingLines}

      // Box
      w: [fluid('${p}-w')],
      h: [fluid('${p}-h')],
      size: [fluid('${p}-size')],
      'min-w': [fluid('${p}-min-w')],
      'min-h': [fluid('${p}-min-h')],
      'max-h': [fluid('${p}-max-h')],
      // \`${p}-cap-*\` IS a max-width, however differently it behaves (it
      // only ever grows). A plain \`max-w-*\` next to it is still a conflict.
      'max-w': [fluid('${p}-cap')],

      // Type — all three land in ONE group on purpose: they are three
      // units for one property, so two of them on one element is always a
      // mistake, never an intentional pair.
      'font-size': [fluid('${p}-text'), fluid('${p}-copy'), fluid('${p}-display')],

      // Position
      inset: [fluid('${p}-inset')],
      top: [fluid('${p}-top')],
      right: [fluid('${p}-right')],
      bottom: [fluid('${p}-bottom')],
      left: [fluid('${p}-left')],

      'translate-x': [fluid('${p}-translate-x')],
      'translate-y': [fluid('${p}-translate-y')]
    }
  }
})

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
`
  )
}

