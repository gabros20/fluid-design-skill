function buildUtilityBlock(prefix, cfg) {
  const p = prefix
  return `/* ── Utilities that spend the fluid units ───────────────────────────────
   One @utility per property. The VALUE is always the drawn number, inline
   at the call site — nothing is pre-registered, any number (including
   decimals) works. \`lg:${p}-py-120\` is 120 design px of block padding,
   scaled by --fluid.

   NAMING: every utility is \`${p}-\` plus the name Tailwind already uses for
   that property (\`${p}-p-*\` is \`p-*\`, \`${p}-size-*\` is \`size-*\` — width
   AND height, exactly as Tailwind's own \`size-*\` — \`${p}-text-*\` is
   \`text-*\`, font-size). Nothing here invents a word where Tailwind has
   one, so the only thing left to know is WHICH UNIT a class spends.

   \`${p}-cap-*\` is the one exception, and earns it by behaving differently:
   it is a max-width that only ever GROWS, never an ordinary max-width.

${NEGATIVES_NOTE.split('\n').map((l) => '   ' + l).join('\n')}

${NOT_SCALED_NOTE.split('\n').map((l) => '   ' + l).join('\n')}
*/

/* Padding — full set, every axis and side. A half-set (say, missing pl/pr)
   is an oversight waiting to be found by whoever needs the missing side. */
@utility ${p}-p-* {
  padding: calc(--value(number) * var(--fluid));
}
@utility ${p}-px-* {
  padding-inline: calc(--value(number) * var(--fluid));
}
@utility ${p}-py-* {
  padding-block: calc(--value(number) * var(--fluid));
}
@utility ${p}-pt-* {
  padding-top: calc(--value(number) * var(--fluid));
}
@utility ${p}-pb-* {
  padding-bottom: calc(--value(number) * var(--fluid));
}
@utility ${p}-pl-* {
  padding-left: calc(--value(number) * var(--fluid));
}
@utility ${p}-pr-* {
  padding-right: calc(--value(number) * var(--fluid));
}

/* Margin — same full-set reasoning as padding. */
@utility ${p}-m-* {
  margin: calc(--value(number) * var(--fluid));
}
@utility ${p}-mx-* {
  margin-inline: calc(--value(number) * var(--fluid));
}
@utility ${p}-my-* {
  margin-block: calc(--value(number) * var(--fluid));
}
@utility ${p}-mt-* {
  margin-top: calc(--value(number) * var(--fluid));
}
@utility ${p}-mb-* {
  margin-bottom: calc(--value(number) * var(--fluid));
}
@utility ${p}-ml-* {
  margin-left: calc(--value(number) * var(--fluid));
}
@utility ${p}-mr-* {
  margin-right: calc(--value(number) * var(--fluid));
}

@utility ${p}-gap-* {
  gap: calc(--value(number) * var(--fluid));
}
@utility ${p}-gap-y-* {
  row-gap: calc(--value(number) * var(--fluid));
}
/* gap-x scales too — horizontal space INSIDE a box that itself scales is
   part of the drawing, same as vertical space. (Space between page-level
   COLUMNS is a different call: that's a page-gutter concern and should
   follow the breakpoint, not this scale — leave that plain \`gap-x-*\`.) */
@utility ${p}-gap-x-* {
  column-gap: calc(--value(number) * var(--fluid));
}

@utility ${p}-w-* {
  width: calc(--value(number) * var(--fluid));
}
@utility ${p}-h-* {
  height: calc(--value(number) * var(--fluid));
}
/* Square: width AND height in one utility, for icons and marks — a fixed
   16px icon beside type that scales reads 30% small on a large display. */
@utility ${p}-size-* {
  width: calc(--value(number) * var(--fluid));
  height: calc(--value(number) * var(--fluid));
}
/* A floor that scales. \`${p}-min-w-166\` on a button primitive is that
   component's frame width — left fixed it would stop being a floor once
   the rest of the composition has outgrown it. */
@utility ${p}-min-w-* {
  min-width: calc(--value(number) * var(--fluid));
}
@utility ${p}-min-h-* {
  min-height: calc(--value(number) * var(--fluid));
}
@utility ${p}-max-h-* {
  max-height: calc(--value(number) * var(--fluid));
}

/* A width CAP that only ever grows. Below the reference the drawn number
   already fits the viewport and shrinking it would narrow the composition
   on exactly the screens that need the room; above it the cap has to scale
   or the frame gets taller without getting wider. */
@utility ${p}-cap-* {
  max-width: max(calc(--value(number) * 1px), calc(--value(number) * var(--fluid)));
}

/* Offsets for absolutely-positioned parts drawn at fixed coordinates inside
   a composition that scales — \`inset-0\` and percentage offsets need none
   of this; zero and 50% are already relative. */
@utility ${p}-inset-* {
  inset: calc(--value(number) * var(--fluid));
}
@utility ${p}-top-* {
  top: calc(--value(number) * var(--fluid));
}
@utility ${p}-right-* {
  right: calc(--value(number) * var(--fluid));
}
@utility ${p}-bottom-* {
  bottom: calc(--value(number) * var(--fluid));
}
@utility ${p}-left-* {
  left: calc(--value(number) * var(--fluid));
}

/* Writes the independent \`translate\` property, not \`transform\`, so it
   composes with a transform a motion library writes per frame instead of
   fighting it for the same property. */
@utility ${p}-translate-x-* {
  --tw-translate-x: calc(--value(number) * var(--fluid));
  translate: var(--tw-translate-x) var(--tw-translate-y);
}
@utility ${p}-translate-y-* {
  --tw-translate-y: calc(--value(number) * var(--fluid));
  translate: var(--tw-translate-x) var(--tw-translate-y);
}

/* Type. The \`/\` modifier is Tailwind's own \`text-lg/7\` idiom:
   \`${p}-display-64/72\` is 64px type on a 72px line box, BOTH scaled
   together. Omit it and only font-size is emitted.
   \`${p}-display-*\` and \`${p}-copy-*\` spend the damped type units;
   \`${p}-text-*\` spends the BASE unit, for type whose container scales on
   it too — type on the gentler curve inside a box on the steeper one
   outgrows its box and re-wraps.${cfg.zoomCompensation ? `
   Browser zoom: display and copy zoom 1:1 through their units. \`${p}-text-*\`
   takes a share of the zoom by size — all of it up to ${num(cfg.zoomTextRange[0])}px drawn,
   none from ${num(cfg.zoomTextRange[1])}px — because its box does not zoom, and big type
   zoomed inside it runs over its neighbours (zoomTextRange, fluid-scale.md §12).` : ''} */
@utility ${p}-display-* {
  font-size: calc(--value(number) * var(--fluid-display));
  line-height: calc(--modifier(number) * var(--fluid-display));
}
@utility ${p}-copy-* {
  font-size: calc(--value(number) * var(--fluid-copy));
  line-height: calc(--modifier(number) * var(--fluid-copy));
}
@utility ${p}-text-* {
  font-size: calc(--value(number) * ${textUnitExprRuntime(cfg, '--value(number)')});
  line-height: calc(--modifier(number) * ${textUnitExprRuntime(cfg, '--value(number)')});
}
`
}

