// ── shared text fragments ──────────────────────────────────────────────

function configSummary(cfg) {
  const floors = resolveFloors(cfg)
  const lines = [
    `reference ${num(cfg.reference.width)}x${num(cfg.reference.height)}, canvas ${num(cfg.canvas.width)}/${num(cfg.canvas.gutter)}, engageAt ${num(cfg.engageAt)}, heightAxis ${cfg.heightAxis}`,
    `fluid.floor ${num(floors.fluid)}`,
    `display.damping ${num(cfg.units.display.damping)} (floor ${cfg.units.display.floor === 'auto' ? `auto -> ${num(floors.display)}` : num(floors.display)})`,
    `copy.damping ${num(cfg.units.copy.damping)} (floor ${cfg.units.copy.floor === 'auto' ? `auto -> ${num(floors.copy)}` : num(floors.copy)})`,
    `chrome.enabled ${cfg.units.chrome.enabled}`,
    `ceiling ${cfg.ceiling === null ? 'none' : num(cfg.ceiling)}`,
    `prefix "${cfg.prefix}"`
  ]
  return lines
}

