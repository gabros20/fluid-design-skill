// ── CLI ─────────────────────────────────────────────────────────────────

function parseArgs(argv) {
  const args = { stack: null, config: undefined, out: DEFAULT_OUT_DIR, check: false }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--config') args.config = argv[++i]
    else if (a === '--stack') args.stack = argv[++i]
    else if (a === '--out') args.out = resolvePath(argv[++i])
    else if (a === '--check') args.check = true
    else throw new Error(`unrecognised argument "${a}"`)
  }
  return args
}

function stacksToBuild(stack) {
  if (stack === 'all' || stack == null) return STACKS
  if (!STACKS.includes(stack)) {
    throw new Error(`unknown --stack "${stack}", expected one of: ${STACKS.join(', ')}, all`)
  }
  return [stack]
}

function buildFiles(cfg, stacks) {
  /** @type {Record<string, string>} */
  const files = {}
  if (stacks.includes('tailwind-v4')) {
    files['tailwind-v4/fluid.css'] = buildTailwindFluidCss(cfg)
    files['tailwind-v4/tokens.example.css'] = buildTokensExampleCss(cfg)
    files['tailwind-v4/cn.ts'] = buildCnTs(cfg)
    files['tailwind-v4/README.md'] = buildTailwindReadme(cfg)
  }
  if (stacks.includes('css')) {
    files['css/fluid.css'] = buildVanillaCss(cfg)
    files['css/README.md'] = buildVanillaReadme(cfg)
  }
  if (stacks.includes('scss')) {
    files['scss/_fluid.scss'] = buildScss(cfg)
    files['scss/README.md'] = buildScssReadme(cfg)
  }
  if (stacks.includes('stylex')) {
    files['stylex/fluid.stylex.ts'] = buildStylex(cfg)
    files['stylex/README.md'] = buildStylexReadme(cfg)
  }
  // shared/base.css is stack-agnostic and always (re)generated, regardless
  // of which stack(s) were requested.
  files['shared/base.css'] = buildSharedBaseCss(cfg)
  return files
}

function main() {
  const args = parseArgs(process.argv.slice(2))

  if (args.check) {
    const cfg = loadConfig(DEFAULT_CONFIG_PATH)
    const files = buildFiles(cfg, STACKS)
    const mismatches = []
    for (const [rel, expected] of Object.entries(files)) {
      const abs = join(DEFAULT_OUT_DIR, rel)
      if (!existsSync(abs)) {
        mismatches.push(`missing: ${rel}`)
        continue
      }
      const actual = readFileSync(abs, 'utf8')
      if (actual !== expected) {
        mismatches.push(`stale: ${rel}`)
      }
    }
    if (mismatches.length > 0) {
      console.error('[fluid-design] --check found differences:')
      for (const m of mismatches) console.error(`  ${m}`)
      console.error('Run: node scripts/generate-fluid.mjs --stack all')
      process.exit(1)
    }
    console.log('[fluid-design] --check OK — assets/styles matches the default config.')
    return
  }

  const cfg = loadConfig(args.config)
  const stacks = stacksToBuild(args.stack)
  const files = buildFiles(cfg, stacks)

  for (const [rel, content] of Object.entries(files)) {
    const abs = join(args.out, rel)
    mkdirSync(dirname(abs), { recursive: true })
    writeFileSync(abs, content)
  }

  console.log(`[fluid-design] wrote ${Object.keys(files).length} file(s) to ${args.out}`)
}

main()
